-- Shared identity + isolated application membership.
-- Safe to run repeatedly. It does not alter or delete existing project tables.

create table if not exists public.shared_accounts (
  id bigint generated by default as identity primary key,
  first_name text not null default '',
  last_name text not null default '',
  employee_id text not null unique,
  branch text not null default '',
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.app_memberships (
  id bigint generated by default as identity primary key,
  account_id bigint not null references public.shared_accounts(id) on delete cascade,
  app_id text not null,
  role text not null default 'user'
    check (role in ('admin', 'user', 'contractor')),
  approved boolean not null default false,
  created_at timestamptz not null default now(),
  unique (account_id, app_id)
);

create index if not exists app_memberships_app_id_idx
  on public.app_memberships (app_id);

alter table public.shared_accounts enable row level security;
alter table public.app_memberships enable row level security;

revoke all on table public.shared_accounts from anon;
revoke all on table public.shared_accounts from authenticated;
revoke all on table public.app_memberships from anon;
revoke all on table public.app_memberships from authenticated;

comment on table public.shared_accounts is
  'Shared username/password identities. Never store project-specific roles here.';
comment on table public.app_memberships is
  'Role and approval isolated by app_id. Deleting one app membership does not delete the shared account.';
